#![forbid(unsafe_code)]

#[path = "../app_info/contracts.rs"]
mod app_info_contracts;
#[path = "../app_info/command_name.rs"]
mod command_name;
#[path = "../contracts.rs"]
mod contracts;
#[path = "../ivy/wire.rs"]
mod ivy;
#[path = "../speech/contracts.rs"]
mod speech;
#[path = "../speech/command_names.rs"]
mod speech_names;

use app_info_contracts::{
    APP_INFO_EVENT, AppCapability, AppInfoError, AppInfoEvent, AppInfoReply, AppInfoRequest,
};
use command_name::APP_INFO_COMMAND;
use contracts::{ShellError, ShellReply, ShellRequest};
use ivy::contracts::*;
use ivy::presentation::{IvyComponent, IvyPresentation};
use ivy::workspace_contracts::*;
use speech::*;
use ts_rs::TS;

fn main() {
    let config = ts_rs::Config::default();
    println!("// Generated by ts-rs 12.0.1 from the desktop Rust contracts. Do not edit.");
    for definition in [
        ShellRequest::decl(&config),
        ShellReply::decl(&config),
        ShellError::decl(&config),
        AppCapability::decl(&config),
        AppInfoRequest::decl(&config),
        AppInfoReply::decl(&config),
        AppInfoError::decl(&config),
        AppInfoEvent::decl(&config),
        IvyConnectionState::decl(&config),
        WorkspaceToolsState::decl(&config),
        IvyTurnState::decl(&config),
        IvyErrorCode::decl(&config),
        IvyModel::decl(&config),
        IvySelectRequest::decl(&config),
        IvyRequest::decl(&config),
        IvySubmitRequest::decl(&config),
        IvyComponent::decl(&config),
        IvyPresentation::decl(&config),
        IvySnapshot::decl(&config),
        WorkspaceSurface::decl(&config),
        WorkspaceProminence::decl(&config),
        WorkspaceToolOperation::decl(&config),
        WorkspaceToolRequest::decl(&config),
        WorkspacePaneMetadata::decl(&config),
        WorkspaceToolOutcome::decl(&config),
        WorkspaceToolReply::decl(&config),
        SpeechState::decl(&config),
        SpeechError::decl(&config),
        SpeechRequest::decl(&config),
        SpeechStopRequest::decl(&config),
        SpeechTranscribeRequest::decl(&config),
        SpeechTranscript::decl(&config),
        SpeechSpeakRequest::decl(&config),
        SpeechSnapshot::decl(&config),
    ] {
        let definition = definition
            .lines()
            .map(str::trim_end)
            .collect::<Vec<_>>()
            .join("\n");
        println!("export {definition}");
    }
    println!(
        "export const appInfoCommand = {} as const;",
        serde_json::to_string(APP_INFO_COMMAND).unwrap()
    );
    println!(
        "export const appInfoEvent = {} as const;",
        serde_json::to_string(APP_INFO_EVENT).unwrap()
    );
    println!(
        "export type DesktopCommands = {{ [appInfoCommand]: {{ request: AppInfoRequest; reply: AppInfoReply }} }};"
    );
    println!("export type DesktopEvents = {{ [appInfoEvent]: AppInfoEvent }};");
    for (name, command) in [
        "ivyConnectCommand",
        "ivySnapshotCommand",
        "ivySubmitCommand",
        "ivyCancelCommand",
        "ivyReconcileCommand",
        "ivyDisconnectCommand",
        "ivySelectSessionCommand",
        "ivyClearConversationCommand",
    ]
    .iter()
    .zip(IVY_COMMANDS)
    {
        println!(
            "export const {name} = {} as const;",
            serde_json::to_string(command).unwrap()
        );
    }
    println!(
        "export const ivyEvent = {} as const;",
        serde_json::to_string(IVY_EVENT).unwrap()
    );
    println!(
        "export const workspaceToolEvent = {} as const;",
        serde_json::to_string(WORKSPACE_EVENT).unwrap()
    );
    println!(
        "export const workspaceToolReplyCommand = {} as const;",
        serde_json::to_string(WORKSPACE_REPLY_COMMAND).unwrap()
    );
    println!(
        "export type IvyCommands = {{ [ivyConnectCommand]: IvyRequest; [ivySnapshotCommand]: IvyRequest; [ivySubmitCommand]: IvySubmitRequest; [ivyCancelCommand]: IvyRequest; [ivyReconcileCommand]: IvyRequest; [ivyDisconnectCommand]: IvyRequest; [ivySelectSessionCommand]: IvySelectRequest; [ivyClearConversationCommand]: IvyRequest }};"
    );
    for (name, command) in [
        "speechTranscribeCommand",
        "speechSpeakCommand",
        "speechStopCommand",
        "speechSnapshotCommand",
    ]
    .iter()
    .zip(speech_names::SPEECH_COMMANDS)
    {
        println!(
            "export const {name} = {} as const;",
            serde_json::to_string(command).unwrap()
        );
    }
    println!(
        "export const speechEvent = {} as const;",
        serde_json::to_string(SPEECH_EVENT).unwrap()
    );
    println!(
        "export type SpeechCommands = {{ [speechTranscribeCommand]: SpeechTranscribeRequest; [speechSpeakCommand]: SpeechSpeakRequest; [speechStopCommand]: SpeechStopRequest; [speechSnapshotCommand]: SpeechRequest }};"
    );
}
